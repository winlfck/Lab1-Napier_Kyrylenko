#!/bin/bash

# 1. Запит назви файлу
echo -n "Введіть назву файлу для видалення: "
read FILENAME

# 2. Перевірка наявності файлу
if [ ! -e "$FILENAME" ]; then
    echo "Помилка: Файл '$FILENAME' не існує."
    exit 1
fi

# 3. Перевірка довжини назви (> 12 - помилка)
if [ ${#FILENAME} -gt 12 ]; then
    echo "Помилка: Довжина назви перевищує 12 символів."
    exit 1
fi

# 4. Перевірка цифр підряд (> 9 цифр - помилка)
# Регулярний вираз [0-9]{10,} шукає 10 або більше цифр
if [[ "$FILENAME" =~ [0-9]{10,} ]]; then
    echo "Помилка: Назва містить більше 9 цифр підряд."
    exit 1
fi

# 5. Видалення файлу
rm "$FILENAME"
echo "Файл '$FILENAME' успішно видалено."
